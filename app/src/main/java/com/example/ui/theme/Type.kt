val DevanagariFontFamily = FontFamily(
    Font(R.font.noto_sans_devanagari, FontWeight.Normal),
    Font(R.font.noto_sans_devanagari, FontWeight.Medium),
    Font(R.font.noto_sans_devanagari, FontWeight.SemiBold),
    Font(R.font.noto_sans_devanagari, FontWeight.Bold)
)

private val devanagariRegex = Regex("[\\u0900-\\u097F]")

fun containsDevanagari(text: String): Boolean = devanagariRegex.containsMatchIn(text)

fun adaptiveFontFamily(text: String, preferDisplay: Boolean = false): FontFamily {
    return when {
        containsDevanagari(text) -> DevanagariFontFamily
        preferDisplay -> SpaceGroteskFontFamily
        else -> PlusJakartaFontFamily
    }
}

